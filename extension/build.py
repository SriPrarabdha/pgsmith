#!/usr/bin/env python3
"""Build pg_flagsmith into a single SQL install script, a pg_tle installer and a
database.dev package.

    python extension/build.py            # writes extension/dist/*

Unicode tables (Python's int()/float() digit and whitespace sets, and the
\\d \\s \\w classes of Python's `re`) are generated here from the running
Python's unicodedata, so build with the Python version your SDKs use (3.12 by
default). Everything is emitted as ASCII escapes, so the SQL file is plain
ASCII.
"""
from __future__ import annotations

import pathlib
import re
import sys
import unicodedata

HERE = pathlib.Path(__file__).resolve().parent
SQL_DIR = HERE / "sql"
DIST = HERE / "dist"
NAME = "pg_flagsmith"
VERSION = (HERE / "VERSION").read_text().strip()
DESCRIPTION = "Flagsmith feature flag evaluation inside Postgres, with parity to the official engine"


def _ranges(pred) -> list[tuple[int, int]]:
    out, start = [], None
    for i in range(0x110000):
        ok = not (0xD800 <= i <= 0xDFFF) and pred(chr(i))
        if ok and start is None:
            start = i
        elif not ok and start is not None:
            out.append((start, i - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def _complement(rs: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out, nxt = [], 1  # never include U+0000 (not representable in Postgres text)
    for lo, hi in rs:
        if lo > nxt:
            out.append((nxt, lo - 1))
        nxt = max(nxt, hi + 1)
    if nxt <= 0x10FFFF:
        out.append((nxt, 0x10FFFF))
    # drop the surrogate block
    res = []
    for lo, hi in out:
        if hi < 0xD800 or lo > 0xDFFF:
            res.append((lo, hi))
        else:
            if lo < 0xD800:
                res.append((lo, 0xD7FF))
            if hi > 0xDFFF:
                res.append((0xE000, hi))
    return res


def _are_char(cp: int) -> str:
    return f"\\u{cp:04x}" if cp <= 0xFFFF else f"\\U{cp:08x}"


def _are_ranges(rs: list[tuple[int, int]]) -> str:
    parts = []
    for lo, hi in rs:
        parts.append(_are_char(lo) if lo == hi else f"{_are_char(lo)}-{_are_char(hi)}")
    return "".join(parts)


def _sql_e(s: str) -> str:
    """An E'' literal for s, ASCII only."""
    out = []
    for ch in s:
        cp = ord(ch)
        if ch == "'":
            out.append("''")
        elif ch == "\\":
            out.append("\\\\")
        elif 0x20 <= cp < 0x7F:
            out.append(ch)
        elif cp <= 0xFFFF:
            out.append(f"\\u{cp:04x}")
        else:
            out.append(f"\\U{cp:08x}")
    return "E'" + "".join(out) + "'"


def unicode_sql() -> str:
    # Characters Python's int() / float() strip (str.isspace minus \x1c-\x1f).
    def _strips(c: str) -> bool:
        try:
            int(c + "1" + c)
            return True
        except ValueError:
            return False

    ws = [chr(i) for i in range(0x110000) if not (0xD800 <= i <= 0xDFFF) and chr(i).isspace() and _strips(chr(i))]
    non_ascii_ws = [c for c in ws if ord(c) > 0x7F]
    digits = [chr(i) for i in range(0x80, 0x110000)
              if not (0xD800 <= i <= 0xDFFF) and unicodedata.decimal(chr(i), None) is not None]
    tr_from = "".join(non_ascii_ws) + "".join(digits)
    tr_to = " " * len(non_ascii_ws) + "".join(str(unicodedata.decimal(c)) for c in digits)

    w = _ranges(lambda c: re.match(r"\w", c) is not None)
    d = _ranges(lambda c: re.match(r"\d", c) is not None)
    s = _ranges(lambda c: re.match(r"\s", c) is not None)
    classes = {
        "w": _are_ranges(w), "W": _are_ranges(_complement(w)),
        "d": _are_ranges(d), "D": _are_ranges(_complement(d)),
        "s": _are_ranges(s), "S": _are_ranges(_complement(s)),
    }
    lines = [
        f"-- Generated by extension/build.py from Python {sys.version.split()[0]}, "
        f"Unicode {unicodedata.unidata_version}. Do not edit.",
        "",
        "-- Python int()/float() accept Unicode whitespace and decimal digits; these map them to ASCII.",
        "CREATE FUNCTION flagsmith._py_num_tr_from() RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE",
        f"BEGIN ATOMIC SELECT {_sql_e(tr_from)}::text; END;",
        "CREATE FUNCTION flagsmith._py_num_tr_to() RETURNS text LANGUAGE sql IMMUTABLE PARALLEL SAFE",
        f"BEGIN ATOMIC SELECT {_sql_e(tr_to)}::text; END;",
        "",
        "-- Bracket-expression bodies (ARE escapes) for Python re's \\w \\W \\d \\D \\s \\S (str patterns).",
        "CREATE FUNCTION flagsmith._re_class(c text) RETURNS text LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE",
        "BEGIN ATOMIC",
        "  SELECT CASE c",
    ]
    for k, v in classes.items():
        lines.append(f"    WHEN {_sql_e(k)} THEN {_sql_e(v)}")
    lines += ["  END;", "END;", ""]
    return "\n".join(lines)


def build() -> pathlib.Path:
    DIST.mkdir(exist_ok=True)
    parts = [
        f"-- {NAME} {VERSION}: {DESCRIPTION}",
        "-- Generated by extension/build.py; edit extension/sql/*.sql instead.",
        "",
        "\\echo Use \"CREATE EXTENSION pg_flagsmith\" to load this file. \\quit",
        "",
        "-- Resolve every name in this script (including SQL-standard function bodies,",
        "-- which bind at creation) in pg_catalog, never in a schema a user can write to.",
        "-- LOCAL: CREATE EXTENSION restores the caller's search_path afterwards (a plain",
        "-- SET here would outlive the command and change the caller's session).",
        "SET LOCAL search_path = pg_catalog, pg_temp;",
        "",
    ]
    files = sorted(SQL_DIR.glob("*.sql"))
    for f in files:
        body = f.read_text()
        parts.append(f"-- ===== {f.name} =====")
        parts.append(body.replace("@@VERSION@@", VERSION))
        if f.name.startswith("00_"):
            parts.append("-- ===== generated unicode tables =====")
            parts.append(unicode_sql())
    script = "\n".join(parts)
    if "$_pgtle_$" in script:
        raise SystemExit("the script must not contain the pg_tle dollar-quote tag")
    try:
        script.encode("ascii")
    except UnicodeEncodeError as e:  # keep the file encoding-neutral
        raise SystemExit(f"non-ASCII character in SQL sources: {e}")

    ext_sql = DIST / f"{NAME}--{VERSION}.sql"
    ext_sql.write_text(script)

    # Plain-extension control file (also next to the PGXS Makefile).
    control = (
        f"comment = '{DESCRIPTION}'\n"
        f"default_version = '{VERSION}'\n"
        "relocatable = false\n"
        "superuser = false\n"
        "trusted = true\n"
    )
    (HERE / f"{NAME}.control").write_text(control)
    (DIST / f"{NAME}.control").write_text(
        f"comment = '{DESCRIPTION}'\n"
        f"default_version = '{VERSION}'\n"
        "relocatable = false\n"
        "superuser = false\n"
        "trusted = true\n"
    )

    # pg_tle installer: works on Supabase and Amazon RDS / Aurora.
    body = script.split("\\quit", 1)[1]
    (DIST / f"{NAME}--{VERSION}.pgtle.sql").write_text(
        f"-- Install {NAME} {VERSION} as a Trusted Language Extension (pg_tle).\n"
        "-- Supabase: pg_tle is preinstalled. Amazon RDS/Aurora: add pg_tle to shared_preload_libraries\n"
        "-- and run this as a member of pgtle_admin.\n"
        "CREATE EXTENSION IF NOT EXISTS pg_tle;\n"
        f"SELECT pgtle.install_extension(\n  '{NAME}',\n  '{VERSION}',\n  '{DESCRIPTION}',\n"
        f"$_pgtle_${body}$_pgtle_$\n);\n"
        f"CREATE EXTENSION {NAME};\n"
    )

    # database.dev (dbdev) package layout.
    pkg = DIST / "dbdev"
    pkg.mkdir(exist_ok=True)
    (pkg / f"{NAME}--{VERSION}.sql").write_text(body.lstrip())
    # dbdev reads `key = value` lines (one '=' each); no `requires` line: an empty one
    # would become a dependency on an extension named ''.
    (pkg / f"{NAME}.control").write_text(
        f"comment = '{DESCRIPTION}'\ndefault_version = '{VERSION}'\nrelocatable = false\nsuperuser = false\n"
    )
    readme = HERE.parent / "README.md"
    if readme.exists():
        (pkg / "README.md").write_text(readme.read_text())
    return ext_sql


if __name__ == "__main__":
    out = build()
    print(f"wrote {out} ({out.stat().st_size:,} bytes)")
